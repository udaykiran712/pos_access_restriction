/** @odoo-module */

import { PosStore } from "@point_of_sale/app/store/pos_store";
import { patch } from "@web/core/utils/patch";

/**
 * Patching PosStore to intercept the manual lot/serial selection popup (EditListPopup).
 * This patch queries the backend for the oldest available stock (FEFO/FIFO) and
 * automatically maps the returned lots to the order lines, completely bypassing the UI interruption.
 */
patch(PosStore.prototype, {
    async editLots(product, packLotLinesToEdit) {
        try {
            const lines = packLotLinesToEdit || [];

            // Identify serials that have already been assigned to this cart line
            const existingLots = lines.filter(line => line.text).map(line => line.text);

            // Calculate the number of empty lot inputs generated by Odoo for this quantity increment
            const emptyLinesCount = lines.filter(line => !line.text).length;

            // Determine required lot quantity: 1 for new lines, or match the empty slots for increments
            const neededQty = emptyLinesCount > 0 ? emptyLinesCount : 1;

            // Proceed with auto-assignment if it is a fresh product addition or requires filling blank slots
            if (lines.length === 0 || emptyLinesCount > 0) {
                const configId = this.config.id;

                // Request the required number of lots/serials from the Python backend
                const assignedLots = await this.env.services.orm.call(
                    'pos.session',
                    'get_fefo_lot_for_pos',
                    [product.id, configId, existingLots, neededQty]
                );

                if (assignedLots && assignedLots.length > 0) {
                    // Retain previously assigned serials to prevent overwriting existing data
                    const modifiedPackLotLines = Object.fromEntries(
                        lines.filter(item => item.id && item.text).map(item => [item.id, item.text])
                    );

                    // Map the newly fetched serials into the payload format expected by Odoo
                    const newPackLotLines = assignedLots.map(lotName => ({ lot_name: lotName }));

                    // Returning this specific object structure explicitly bypasses the native EditListPopup
                    return { modifiedPackLotLines, newPackLotLines };
                }
            }
        } catch (error) {
            console.error("POS Auto Lot Selection - Assignment Error: ", error);
        }

        // Fallback: Execute the standard Odoo behavior if stock is depleted, untracked, or an error occurs
        return super.editLots(product, packLotLinesToEdit);
    }
});